static const uint8_t kEngines[] = { ZWASM_ENGINE_INTERP, ZWASM_ENGINE_JIT, ZWASM_ENGINE_AUTO };

static const char* engine_name(uint8_t kind) {
    switch (kind) {
        case ZWASM_ENGINE_JIT: return "jit";
        case ZWASM_ENGINE_INTERP: return "interp";
        default: return "auto";
    }
}

/* Link the pair in one store, call the importer's `test`, expect `want`. */
static int run_throw_pair(uint8_t engine, const char* label,
                          const uint8_t* ewasm, size_t elen,
                          const uint8_t* iwasm, size_t ilen,
                          int32_t want, int want_trap) {
    int rc = 1;
    const char* who = engine_name(engine);
    wasm_module_t* em = NULL; wasm_instance_t* ei = NULL; wasm_extern_vec_t ex = { 0, NULL };
    wasm_module_t* im = NULL; wasm_instance_t* ii = NULL; wasm_extern_vec_t ix = { 0, NULL };
    wasm_engine_t* eng = wasm_engine_new();
    wasm_store_t* store = eng ? wasm_store_new(eng) : NULL;
    if (!eng || !store) { fputs("engine/store new failed\n", stderr); goto cleanup; }

    wasm_byte_vec_t eb = { elen, (wasm_byte_t*) ewasm };
    em = wasm_module_new(store, &eb);
    if (!em) { fprintf(stderr, "[%s/%s] exporter failed to parse\n", who, label); goto cleanup; }
    wasm_extern_vec_t none = { 0, NULL };
    wasm_trap_t* et = NULL;
    ei = zwasm_instance_new_ex(store, em, &none, &et, engine);
    if (et) wasm_trap_delete(et);
    if (!ei) { fprintf(stderr, "[%s/%s] exporter failed to instantiate\n", who, label); goto cleanup; }
    wasm_instance_exports(ei, &ex);
    if (ex.size < 1 || !ex.data[0]) { fprintf(stderr, "[%s/%s] exporter is missing `boom`\n", who, label); goto cleanup; }

    wasm_byte_vec_t ib = { ilen, (wasm_byte_t*) iwasm };
    im = wasm_module_new(store, &ib);
    if (!im) { fprintf(stderr, "[%s/%s] importer failed to parse\n", who, label); goto cleanup; }
    wasm_extern_t* picked[1] = { ex.data[0] };
    wasm_extern_vec_t imports = { 1, picked };
    wasm_trap_t* it = NULL;
    ii = zwasm_instance_new_ex(store, im, &imports, &it, engine);
    if (it) wasm_trap_delete(it);
    if (!ii) { fprintf(stderr, "[%s/%s] importer failed to instantiate\n", who, label); goto cleanup; }
    wasm_instance_exports(ii, &ix);
    if (ix.size < 1 || !ix.data[0]) { fprintf(stderr, "[%s/%s] importer is missing `test`\n", who, label); goto cleanup; }

    wasm_val_t results[1] = { { WASM_I32, { 0 } } };
    wasm_val_vec_t no_args = { 0, NULL };
    wasm_val_vec_t res = { 1, results };
    wasm_trap_t* trap = wasm_func_call(wasm_extern_as_func(ix.data[0]), &no_args, &res);
    if (want_trap) {
        /* The expected outcome IS the trap: nothing in this module may catch
         * the rethrown identity. A value coming back means it was caught. */
        if (!trap) {
            fprintf(stderr, "[%s/%s] expected a trap, got value=%d\n", who, label, (int) results[0].of.i32);
            goto cleanup;
        }
        wasm_trap_delete(trap);
        rc = 0;
        goto cleanup;
    }
    if (trap) {
        fprintf(stderr, "[%s/%s] the throw escaped the importer's catch_all as a trap\n", who, label);
        wasm_trap_delete(trap);
        goto cleanup;
    }
    if (results[0].kind != WASM_I32 || results[0].of.i32 != want) {
        fprintf(stderr, "[%s/%s] expected %d from the handler, got kind=%d value=%d\n",
                who, label, (int) want, (int) results[0].kind, (int) results[0].of.i32);
        goto cleanup;
    }
    rc = 0;

cleanup:
    if (ix.data) wasm_extern_vec_delete(&ix);
    if (ii) wasm_instance_delete(ii);
    if (im) wasm_module_delete(im);
    if (ex.data) wasm_extern_vec_delete(&ex);
    if (ei) wasm_instance_delete(ei);
    if (em) wasm_module_delete(em);
    if (store) wasm_store_delete(store);
    if (eng) wasm_engine_delete(eng);
    return rc;
}

int main(void) {
    for (size_t i = 0; i < sizeof(kEngines) / sizeof(kEngines[0]); i++) {
        if (run_throw_pair(kEngines[i], "catch", kThrowExporterWasm, sizeof(kThrowExporterWasm),
                           kCatchImporterWasm, sizeof(kCatchImporterWasm), 42, 0) != 0) return 1;
        if (run_throw_pair(kEngines[i], "glob", kGlobThrowExporterWasm, sizeof(kGlobThrowExporterWasm),
                           kGlobCatchImporterWasm, sizeof(kGlobCatchImporterWasm), 7, 0) != 0) return 1;
        if (run_throw_pair(kEngines[i], "rethrow", kTwoTagExporterWasm, sizeof(kTwoTagExporterWasm),
                           kRethrowImporterWasm, sizeof(kRethrowImporterWasm), 0, 1) != 0) return 1;
        if (run_throw_pair(kEngines[i], "local", kOwnTagExporterWasm, sizeof(kOwnTagExporterWasm),
                           kLocalRethrowImporterWasm, sizeof(kLocalRethrowImporterWasm), 55, 0) != 0) return 1;
    }
    return 0;
}
