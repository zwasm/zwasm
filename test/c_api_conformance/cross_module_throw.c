/* zwasm v2 — C-API conformance: a throw inside an imported function reaches
 * the importer's handler across the bridge (#426, ADR-0134 D2).
 *
 * The exporter declares its own tag and throws it; the importer calls the
 * import inside a `try_table (catch_all $h)` and returns 42 from the handler
 * (-1 if control ever came back normally). Both instances live in ONE store,
 * linked through the C API exactly as an embedder links them.
 *
 * On the JIT the unwinder asks the process-global EH registry which instance
 * owns each frame's PC. The C API never registered, so the registry was empty:
 * no handler was found and the walk carried on into host frames until it
 * faulted. `interp` was the only engine that answered 42.
 *
 * The `rethrow` pair asks whose TAG SPACE a reified exnref belongs to. Tag
 * indices are per module and `Exception` records no owner, so carrying the
 * throwing module's index across had a later `throw_ref` resolve that number
 * among the CATCHING module's tags: A throws its tag 1, B holds a different
 * tag at 1, and B's own handler for it caught the rethrow (42 where the
 * interpreter traps). The index now crosses as the identity the unwinder
 * matches on, and an identity B does not declare is uncaught.
 *
 * The `local` pair asks whether the identity is left behind. It is written for
 * every handler, not only a cross-instance one: written conditionally, this
 * runtime kept the FOREIGN identity after catching the exporter's tag, and a
 * later same-instance `catch_all_ref` + `throw_ref` of its OWN tag reified with
 * it — so the rethrow skipped its own handler (trap where 55 is expected).
 *
 * The `glob` pair then asks WHOSE instance the handler runs as. A throw leaves
 * through the bridge thunk's frame instead of returning through it, so the
 * thunk's restore of the caller's pinned runtime never runs: the handler read
 * the THROWING instance's globals — 1000 where the importer's own is 7 (#426
 * review). A constant-returning handler cannot see that, which is why this
 * case reads a global instead.
 *
 * Exits 0 on success.
 */

