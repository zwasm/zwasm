static const uint8_t kEngines[] = { ZWASM_ENGINE_INTERP, ZWASM_ENGINE_JIT, ZWASM_ENGINE_AUTO };

static const char* engine_name(uint8_t kind) {
    switch (kind) {
        case ZWASM_ENGINE_JIT: return "jit";
        case ZWASM_ENGINE_INTERP: return "interp";
        default: return "auto";
    }
}

typedef struct {
    const char* name;
    int32_t expect;
} case_t;

/* Instantiate `exporter` then `importer` (every import is satisfied from the
 * exporter's exports, in import order = export order for these fixtures,
 * except `indirect`, which takes exports 0 and 5), call each named export of
 * the importer and compare. */
static int run_pair(uint8_t engine, const char* label,
                    const uint8_t* ewasm, size_t elen, const uint8_t* iwasm, size_t ilen,
                    const size_t* export_pick, size_t n_imports,
                    const case_t* cases, size_t n_cases) {
    int rc = 1;
    const char* who = engine_name(engine);
    wasm_module_t* em = NULL; wasm_instance_t* ei = NULL; wasm_extern_vec_t ex = { 0, NULL };
    wasm_module_t* im = NULL; wasm_instance_t* ii = NULL; wasm_extern_vec_t ix = { 0, NULL };
    wasm_extern_t* picked[8];
    wasm_engine_t* eng = wasm_engine_new();
    wasm_store_t* store = eng ? wasm_store_new(eng) : NULL;
    if (!eng || !store) { fputs("engine/store new failed\n", stderr); goto cleanup; }

    wasm_byte_vec_t eb = { elen, (wasm_byte_t*) ewasm };
    em = wasm_module_new(store, &eb);
    if (!em) { fprintf(stderr, "[%s/%s] exporter failed to parse\n", who, label); goto cleanup; }
    wasm_extern_vec_t none = { 0, NULL };
    wasm_trap_t* et = NULL;
    ei = zwasm_instance_new_ex(store, em, &none, &et, engine);
    if (et) wasm_trap_delete(et);
    if (!ei) { fprintf(stderr, "[%s/%s] exporter failed to instantiate\n", who, label); goto cleanup; }
    wasm_instance_exports(ei, &ex);
    for (size_t k = 0; k < n_imports; k++) {
        if (export_pick[k] >= ex.size || !ex.data[export_pick[k]]) {
            fprintf(stderr, "[%s/%s] exporter is missing export %zu\n", who, label, export_pick[k]);
            goto cleanup;
        }
        picked[k] = ex.data[export_pick[k]];
    }

    wasm_byte_vec_t ib = { ilen, (wasm_byte_t*) iwasm };
    im = wasm_module_new(store, &ib);
    if (!im) { fprintf(stderr, "[%s/%s] importer failed to parse\n", who, label); goto cleanup; }
    wasm_extern_vec_t imports = { n_imports, picked };
    wasm_trap_t* it = NULL;
    ii = zwasm_instance_new_ex(store, im, &imports, &it, engine);
    if (it) wasm_trap_delete(it);
    if (!ii) {
        fprintf(stderr, "[%s/%s] the importer failed to instantiate — the bridge declined a shape it should carry\n", who, label);
        goto cleanup;
    }
    wasm_instance_exports(ii, &ix);
    if (ix.size < n_cases) { fprintf(stderr, "[%s/%s] importer exposed %zu exports, expected %zu\n", who, label, ix.size, n_cases); goto cleanup; }

    for (size_t k = 0; k < n_cases; k++) {
        wasm_val_t results[1] = { { WASM_I32, { 0 } } };
        wasm_val_vec_t no_args = { 0, NULL };
        wasm_val_vec_t res = { 1, results };
        wasm_trap_t* trap = wasm_func_call(wasm_extern_as_func(ix.data[k]), &no_args, &res);
        if (trap) {
            fprintf(stderr, "[%s/%s] %s trapped\n", who, label, cases[k].name);
            wasm_trap_delete(trap);
            goto cleanup;
        }
        if (results[0].kind != WASM_I32 || results[0].of.i32 != cases[k].expect) {
            fprintf(stderr, "[%s/%s] %s: expected %d, got kind=%d value=%d\n",
                    who, label, cases[k].name, (int) cases[k].expect, (int) results[0].kind, (int) results[0].of.i32);
            goto cleanup;
        }
    }
    rc = 0;

cleanup:
    if (ix.data) wasm_extern_vec_delete(&ix);
    if (ii) wasm_instance_delete(ii);
    if (im) wasm_module_delete(im);
    if (ex.data) wasm_extern_vec_delete(&ex);
    if (ei) wasm_instance_delete(ei);
    if (em) wasm_module_delete(em);
    if (store) wasm_store_delete(store);
    if (eng) wasm_engine_delete(eng);
    return rc;
}

int main(void) {
    static const case_t abi_cases[] = {
        { "test_pick7", 77 }, { "test_sum7", 28 }, { "test_pick9", 99 },
        { "test_mixsum", 595 }, { "test_three", 123 }, { "test_three_of", 147 },
    };
    static const size_t abi_pick[] = { 0, 1, 2, 3, 4, 5 };
    static const case_t indirect_cases[] = {
        { "test_indirect", 77 }, { "test_indirect_three", 147 }, { "test_ref", 77 },
    };
    static const size_t indirect_pick[] = { 0, 5 };
    static const case_t glob_cases[] = { { "test", 8 } };
    static const size_t glob_pick[] = { 0 };
    for (size_t i = 0; i < sizeof(kEngines) / sizeof(kEngines[0]); i++) {
        if (run_pair(kEngines[i], "abi", kAbiExporterWasm, sizeof(kAbiExporterWasm),
                     kAbiImporterWasm, sizeof(kAbiImporterWasm), abi_pick, 6, abi_cases, 6) != 0) return 1;
        if (run_pair(kEngines[i], "indirect", kAbiExporterWasm, sizeof(kAbiExporterWasm),
                     kIndirectImporterWasm, sizeof(kIndirectImporterWasm), indirect_pick, 2, indirect_cases, 3) != 0) return 1;
        if (run_pair(kEngines[i], "globals", kGlobExporterWasm, sizeof(kGlobExporterWasm),
                     kGlobImporterWasm, sizeof(kGlobImporterWasm), glob_pick, 1, glob_cases, 1) != 0) return 1;
    }
    return 0;
}
