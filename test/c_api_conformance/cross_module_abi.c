/* zwasm v2 — C-API conformance: the cross-module bridge carries what the
 * ABI does not pass in registers (#390, ADR-0228).
 *
 * Exporter signatures overflow every convention's register file and return
 * MEMORY-class (three results); the importer pushes constants and folds.
 * Every shape runs on `interp` (no bridge — the oracle), `jit` and `auto`,
 * and all three must agree with the constants below. Before ADR-0228 `auto`
 * and `jit` declined these importers (NULL, the #391 fence); before #391
 * they returned garbage read from the wrong frame.
 *
 *   test_pick7          77    7 × i32, the 7th (SysV / Win64 overflow slot)
 *   test_sum7           28    7 × i32 summed (every slot read once)
 *   test_pick9          99    9 × i32, the 9th (arm64 overflow slot)
 *   test_mixsum        595    6 × i32 + 9 × f64: the two classes overflow on
 *                             different rules per convention
 *   test_three         123    (result i32 i32 i32), folded a*100+b*10+c
 *   test_three_of      147    7 × i32 → three results: overflow AND hidden ptr
 *   test_indirect       77    call_indirect through a table element that is
 *                             the import — the same thunk, reached by funcref
 *   test_indirect_three 147   … with a MEMORY-class result
 *   test_ref            77    call_ref of `ref.func` on the import
 *   glob test            8    #413 — the importer's globals base survives the
 *                             call (arm64 X23); the exporter's would read 1001
 *
 * Exits 0 on success.
 */

