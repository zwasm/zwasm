/* Instantiate `bytes` under AUTO, call `export_idx`, and require the result to
 * equal `want` (i32 when `is64` is 0, else i64). 0 = ok, 1 = mismatch. */
static int check(wasm_store_t* store, const uint8_t* bytes, size_t len, size_t export_idx, int is64, int64_t want, const char* label) {
    wasm_byte_vec_t binary = { len, (wasm_byte_t*) bytes };
    wasm_module_t* module = wasm_module_new(store, &binary);
    if (!module) { fprintf(stderr, "%s: wasm_module_new failed\n", label); return 1; }

    wasm_extern_vec_t imports = { 0, NULL };
    wasm_instance_t* instance = wasm_instance_new(store, module, &imports, NULL);
    int rc = 1;
    if (!instance) { fprintf(stderr, "%s: instantiate failed\n", label); goto drop_module; }

    wasm_extern_vec_t exports = { 0, NULL };
    wasm_instance_exports(instance, &exports);
    if (exports.size <= export_idx) { fprintf(stderr, "%s: missing export\n", label); goto drop_instance; }

    wasm_val_t res[1];
    wasm_val_vec_t no_args = { 0, NULL };
    wasm_val_vec_t results = { 1, res };
    wasm_trap_t* trap = wasm_func_call(wasm_extern_as_func(exports.data[export_idx]), &no_args, &results);
    if (trap) { fprintf(stderr, "%s: trapped\n", label); wasm_trap_delete(trap); goto drop_exports; }

    int64_t got = is64 ? res[0].of.i64 : (int64_t) res[0].of.i32;
    if (got != want) { fprintf(stderr, "%s: got %lld, want %lld\n", label, (long long) got, (long long) want); goto drop_exports; }
    printf("%s: %lld — ok\n", label, (long long) got);
    rc = 0;

drop_exports:
    wasm_extern_vec_delete(&exports);
drop_instance:
    wasm_instance_delete(instance);
drop_module:
    wasm_module_delete(module);
    return rc;
}

int main(void) {
    int rc = 1;
    wasm_engine_t* engine = wasm_engine_new();
    wasm_store_t* store = engine ? wasm_store_new(engine) : NULL;
    if (!engine || !store) { fputs("engine/store new failed\n", stderr); goto cleanup; }

    if (check(store, kArrayNew, sizeof(kArrayNew), 0, 0, 1073741824, "array.new f32")) goto cleanup;
    if (check(store, kArrayNew, sizeof(kArrayNew), 1, 1, 4611686018427387904LL, "array.new f64")) goto cleanup;
    if (check(store, kArrayFill, sizeof(kArrayFill), 0, 0, 1075838976, "array.fill f32")) goto cleanup;
    if (check(store, kArrayFill, sizeof(kArrayFill), 2, 1, 4611686018427387904LL, "array.fill f64")) goto cleanup;
    rc = 0;

cleanup:
    if (store) wasm_store_delete(store);
    if (engine) wasm_engine_delete(engine);
    return rc;
}
