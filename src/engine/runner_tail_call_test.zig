//! #424 — a frame-consuming tail call whose callee needs more than the
//! registers carry is DECLINED by the emit, not miscompiled. The predicate is
//! `codegen/{x86_64,arm64}/op_tail_call.tailFrameCanCarry`, which carries the
//! mechanism; this file pins what it accepts and refuses. Before it,
//! `return_call` returned garbage, `return_call_indirect` trapped `oob_table`
//! and `return_call_ref` died on a fatal signal.
//!
//! **The fixtures are convention-independent on purpose.** The register budget
//! differs per ABI — SysV x86_64 passes 5 user int args, Win64 3, AAPCS64 7 —
//! so a test pinned at 6 params would assert something different on each CI
//! leg. 8 overflow everywhere and 3 fit everywhere. The MEMORY-class case
//! needs no such care: no convention returns three values in registers.
//!
//! NOT covered here: cross-module `return_call $import`, which keeps its frame
//! and so is reserved for rather than refused (`emit_setup`); its regression
//! net is `cross_module_abi.c`'s `tail` case.
//!
//! Module bytes come from `.wat` via `wasm-tools parse`, inlined like
//! `runner_test.zig`'s.

